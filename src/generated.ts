// Files Simien writes into simien/_generated, besides the data model the Rust
// schema engine produces.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

import type { Project } from './project'

/**
 * Types for `simien/schema.ts`'s import of "@simien/client/schema", so the
 * project type-checks (`simien check`) before @simien/client is installed. It
 * describes exactly the schema language the schema engine reads.
 */
export const SCHEMA_TYPES = `// Generated by simien. Do not edit: simien rewrites it.
// Types for simien/schema.ts's imports, until @simien/client provides them.

declare module "@simien/client/schema" {
  /** A field's type. Only the schema engine reads schema.ts; this is for type-checking. */
  export interface Validator<T> {
    readonly __type?: T
  }
  export const v: {
    string(): Validator<string>
    int(): Validator<number>
    float(): Validator<number>
    boolean(): Validator<boolean>
    optional<T>(validator: Validator<T>): Validator<T | null | undefined>
  }
  export type Fields = Record<string, Validator<unknown>>
  export interface TableDefinition<F extends Fields = Fields> {
    readonly kind: "table"
    readonly fields: F
  }
  export interface EdgeDefinition<F extends Fields = Fields> {
    readonly kind: "edge"
    readonly from: string
    readonly to: string
    readonly fields: F
  }
  export function defineTable<F extends Fields>(fields: F): TableDefinition<F>
  export function defineEdge<F extends Fields = {}>(from: string, to: string, fields?: F): EdgeDefinition<F>
  export function defineSchema<S extends Record<string, TableDefinition | EdgeDefinition>>(schema: S): S
}
`

/** Write a file only when its text changed; returns whether it did. */
export function writeIfChanged(file: string, text: string): boolean {
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return false
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, text)
  return true
}

export function writeSchemaTypes(project: Pick<Project, 'generatedDir'>): boolean {
  return writeIfChanged(join(project.generatedDir, 'schema.d.ts'), SCHEMA_TYPES)
}
